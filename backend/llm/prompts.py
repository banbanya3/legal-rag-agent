def build_router_user(query: str, history: list[dict]) -> str:
    """把最近两轮对话压成一行摘要给路由器参考。

    只给两轮：路由只需要知道"用户在说什么事"，给太多反而干扰判断，
    也浪费 token。
    """
    recent = history[-4:]
    if not recent:
        history_text = "（无，这是第一轮对话）"
    else:
        lines = []
        for msg in recent:
            role = "用户" if msg["role"] == "user" else "助手"
            content = (msg.get("content") or "").replace("\n", " ")[:120]
            lines.append(f"{role}：{content}")
        history_text = "\n".join(lines)
    return ROUTER_USER_TEMPLATE.format(history=history_text, query=query)
