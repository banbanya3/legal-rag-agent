"""提示词模板。

法律问答的提示词和通用聊天有本质区别，这里守三条线：

1. **不许编**：只能依据检索到的法条回答，检索不到就明说"知识库未收录"，
   而不是像通用助手那样"根据一般理解"给你编一条。法律场景编造条文的后果太严重。
2. **必须带出处**：每个结论后面标《法律名》第X条，让用户能自己核对。
3. **区分"法律规定"和"实务建议"**：前者必须忠于条文，后者要标明是经验判断。
"""
from __future__ import annotations

from config import LAW_DOMAINS


def _domain_list_text() -> str:
    lines = []
    for key, meta in LAW_DOMAINS.items():
        lines.append(f"- {key}：{meta['label']}（{meta['desc']}）")
    return "\n".join(lines)


